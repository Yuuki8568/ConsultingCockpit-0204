function section(text: string, start: string, end: string, body: string): string {
  const a = text.indexOf(start), b = text.indexOf(end, a + start.length);
  if (a < 0 || b < 0) throw new Error(`承認方針版の元雛形が変わっています: ${start}`);
  return text.slice(0, a) + start + '\n' + body + '\n\n' + text.slice(b);
}
function line(text: string, start: string, replacement: string): string {
  const lines = text.split('\n');
  const index = lines.findIndex((s) => s.startsWith(start));
  if (index < 0) throw new Error(`承認方針版の元雛形が変わっています: ${start}`);
  lines[index] = replacement;
  return lines.join('\n');
}

